/**
 * Supabase Management API helpers (E2E isolated projects).
 */

const API = "https://api.supabase.com/v1";

export function managementHeaders(accessToken) {
  return {
    Authorization: `Bearer ${accessToken}`,
    "Content-Type": "application/json",
  };
}

export async function managementFetch(path, { method = "GET", token, body } = {}) {
  const res = await fetch(`${API}${path}`, {
    method,
    headers: managementHeaders(token),
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  let data = null;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    data = { message: text };
  }
  if (!res.ok) {
    const msg = data?.message || data?.error || `HTTP ${res.status}`;
    throw new Error(`${method} ${path}: ${msg}`);
  }
  return data;
}

export async function listOrganizations(token) {
  return managementFetch("/organizations", { token });
}

export async function createProject(token, { name, organizationSlug, dbPass }) {
  const base = { name, organization_slug: organizationSlug, db_pass: dbPass };
  try {
    return await managementFetch("/projects", {
      method: "POST",
      token,
      body: {
        ...base,
        region_selection: { type: "specific", code: "eu-central-1" },
      },
    });
  } catch (first) {
    return managementFetch("/projects", {
      method: "POST",
      token,
      body: { ...base, region: "eu-central-1" },
    });
  }
}

export async function getProject(token, ref) {
  return managementFetch(`/projects/${ref}`, { token });
}

export async function deleteProject(token, ref) {
  return managementFetch(`/projects/${ref}`, { method: "DELETE", token });
}

export async function waitForProjectActive(token, ref, { maxWaitMs = 300_000, intervalMs = 8_000 } = {}) {
  const start = Date.now();
  while (Date.now() - start < maxWaitMs) {
    const project = await getProject(token, ref);
    const status = (project.status || "").toUpperCase();
    if (status === "ACTIVE" || status === "ACTIVE_HEALTHY") {
      return project;
    }
    await new Promise((r) => setTimeout(r, intervalMs));
  }
  throw new Error(`Project ${ref} did not become active within ${maxWaitMs / 1000}s`);
}

export async function listProjectApiKeys(token, ref) {
  return managementFetch(`/projects/${ref}/api-keys`, { token });
}

/** Run SQL on a remote project (Management API — no direct Postgres / IPv6 required). */
export async function executeProjectSql(token, ref, query) {
  return managementFetch(`/projects/${ref}/database/query`, {
    method: "POST",
    token,
    body: { query },
  });
}

/**
 * Resolve publishable + secret keys from Management API response shapes.
 */
export function extractApiKeys(keysPayload) {
  const items = Array.isArray(keysPayload) ? keysPayload : keysPayload?.data ?? [];
  let publishable = "";
  let secret = "";
  for (const item of items) {
    const name = (item.name || item.type || item.description || "").toLowerCase();
    const val = item.api_key || item.key || item.secret || "";
    if (!val) continue;
    if (name.includes("publishable") || name === "anon" || name.includes("public")) {
      publishable = val;
    }
    if (name.includes("secret") || name === "service_role" || name.includes("service")) {
      secret = val;
    }
  }
  return { publishable, secret };
}

/** Direct host (IPv6 on db.*.supabase.co) — avoid for CLI in WSL/CI without IPv6. */
export function buildDirectDbUrl(ref, dbPass) {
  const enc = encodeURIComponent(dbPass);
  return `postgresql://postgres.${ref}:${enc}@db.${ref}.supabase.co:5432/postgres`;
}

/**
 * Pooler URI — avoids direct db.*.supabase.co when IPv6 is unreachable (WSL/CI).
 * @param {{ port?: 5432 | 6543 }} [options] — 5432 session (migrations, multi-statement SQL); 6543 transaction (runtime)
 */
export function buildPoolerDbUrl(ref, dbPass, region = "eu-central-1", options = {}) {
  const port = options.port ?? 5432;
  const enc = encodeURIComponent(dbPass);
  const host = `aws-1-${region}.pooler.supabase.com`;
  return `postgresql://postgres.${ref}:${enc}@${host}:${port}/postgres`;
}

export function buildE2eEnvFile({ project, dbPass, publishableKey, secretKey }) {
  const ref = project.ref;
  const region =
    project.region ||
    project.region_selection?.code ||
    project.database?.region ||
    "eu-central-1";
  const url = `https://${ref}.supabase.co`;
  const lines = [
    `# Generated by e2e-run — ephemeral project ${project.name}`,
    `E2E_PROJECT_REF=${ref}`,
    `SUPABASE_URL=${url}`,
    `SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
    `VITE_API_BASE_URL=http://127.0.0.1:8787`,
    `SUPABASE_SECRET_KEY=${secretKey}`,
    `SUPABASE_DB_URL=${buildPoolerDbUrl(ref, dbPass, region)}`,
    `SUPABASE_DB_PASSWORD=${dbPass}`,
  ];
  return lines.join("\n") + "\n";
}
